// Creates the DEMO Liberland certificate authority used by /form: a P-256 root key and certificate.
// Its private key is published in demo-ca.js on purpose — anyone can issue "Liberland" certificates
// with it, so verifiers must treat it as a demonstration only. A production CA keeps its key in an HSM.
//
//   node tools/make-demo-ca.mjs      (rewrites demo-ca.js; every previously signed demo PDF stops chaining)
import { writeFileSync } from "node:fs";
import { createRootCertificate, toB64 } from "../lib/core.js";

const keyPair = await crypto.subtle.generateKey({ name: "ECDSA", namedCurve: "P-256" }, true, ["sign", "verify"]);
const der = await createRootCertificate({
  keyPair,
  commonName: "Liberland Citizen Signing CA (DEMO, not trusted)",
  organization: "Liberland (demonstration)",
  years: 10,
});
const jwk = await crypto.subtle.exportKey("jwk", keyPair.privateKey);
const out = `// DEMO certificate authority for liberlandlimited.com/form. Generated by tools/make-demo-ca.mjs.
// The private key below is PUBLIC on purpose: this CA demonstrates the flow and must never be trusted.
window.LL_DEMO_CA = ${JSON.stringify({
  generated: new Date().toISOString(),
  certB64: toB64(der),
  privateJwk: { kty: jwk.kty, crv: jwk.crv, x: jwk.x, y: jwk.y, d: jwk.d },
}, null, 2)};
`;
writeFileSync(new URL("../demo-ca.js", import.meta.url), out);
console.log("demo-ca.js written");
