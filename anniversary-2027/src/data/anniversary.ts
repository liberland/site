/* ==========================================================================
   LIBERLAND 12th ANNIVERSARY 2027 — EVERYTHING EDITABLE LIVES IN THIS FILE
   --------------------------------------------------------------------------
   Change a value, then run `npm run build` (or merge to the deploy branch).
   A mistyped value stops the build with a plain-English message
   (see src/lib/validate.ts), so a mistake cannot silently reach the page.

   Golden rules
   • Dates are ISO (YYYY-MM-DD). Weekdays and "9–12 April 2027" are worked out
     automatically — never type a weekday by hand.
   • Nothing is "confirmed" until the organisers have confirmed it in writing.
     Every status below defaults to the cautious value.
   • Every photograph has a source and credit (see ASSETS.md). A photo with
     `cleared: false` is simply left out — the layout never shows an empty frame.
   ========================================================================== */

/* ---------- Types (you do not normally need to edit these) ---------- */

/** proposed = indicative, shown with a "Provisional" tag · confirmed = organisers confirmed · cancelled = hidden from the page */
export type SessionStatus = 'proposed' | 'confirmed' | 'cancelled';

/** speaker / guest = written confirmation for 2027 · featured = shown as a community figure, NO attendance claim · pending = invited, awaiting reply */
export type ParticipationStatus = 'speaker' | 'guest' | 'featured' | 'pending';

export type Photo = {
  /** File stem in public/images/ (…-<width>.webp), produced by scripts/photos.py. */
  file: string;
  /** Intrinsic size of the largest rendition, for layout stability. */
  width: number;
  height: number;
  /** Widths generated by scripts/photos.py. */
  widths: number[];
  /** CSS object-position, to steer the crop. */
  focus?: string;
  /** Alt text describing only what is actually in the photograph. */
  alt: string;
  /** Short visible caption. Never claims more than is known (dates, places, names). */
  caption?: string;
  /** Credit line collected in the footer. */
  credit: string;
  /** Original source URL (also listed in ASSETS.md). */
  source: string;
  /** false hides the photograph (the layout recomposes without it — there are no placeholders). */
  cleared: boolean;
};

export type Session = {
  title: string;
  description?: string;
  /** "HH:MM" 24-hour, or null while not set → shows "Time TBC". */
  start: string | null;
  end: string | null;
  location: string | null;
  /** ids from `people` below; only people with a confirmed status are ever named on a session. */
  speakerIds: string[];
  status: SessionStatus;
};

export type ProgrammeDay = {
  /** ISO date of the day. */
  date: string;
  title: string;
  lead: string;
  sessions: Session[];
};

export type Person = {
  id: string;
  name: string;
  role: string;
  /** Optional short biography (shown under the role when present). */
  bio: string | null;
  /** Participation for 2027 — see ParticipationStatus. */
  status: ParticipationStatus;
  /** Lower numbers appear first. */
  order: number;
  /** Round portrait, or null: the person is then shown as a typographic profile (never an empty frame). */
  portrait: Photo | null;
};

export type Tier = {
  label: string;
  name: string;
  description: string;
  /** e.g. "€120" — leave null until the organisers approve prices. */
  price: string | null;
  /** Shown instead of a price while price is null. */
  priceNote: string;
  /** preparation = not on sale · open = on sale (needs url) · soldout */
  status: 'preparation' | 'open' | 'soldout';
  url: string | null;
  featured?: boolean;
};

